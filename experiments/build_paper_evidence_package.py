# 6. CONSISTENCY CHECKS
# =============================================================================
def run_consistency_checks(nominal_df, robustness_master, fig_dfs) -> list[str]:
    issues = []

    # all rates in [0,1] proxy check on 0-100 scale in fig CSVs
    for name, df in fig_dfs.items():
        for col in df.columns:
            if col.endswith("_pct") and "success" in col and "ci" not in col:
                if (df[col] < 0).any() or (df[col] > 100).any():
                    issues.append(f"{name}.{col} outside [0,100]")

    # robustness_master: 0<=ci_low<=success<=ci_high<=1
    sub = robustness_master.dropna(subset=["success_rate", "ci_low", "ci_high"])
    bad = sub[~((sub["ci_low"] <= sub["success_rate"] + 1e-9) & (sub["success_rate"] <= sub["ci_high"] + 1e-9))]
    if len(bad):
        issues.append(f"robustness_master: {len(bad)} rows with ci_low<=success<=ci_high violated")
    bad_range = robustness_master[(robustness_master["success_rate"] < 0) | (robustness_master["success_rate"] > 1)]
    if len(bad_range):
        issues.append(f"robustness_master: {len(bad_range)} success_rate values outside [0,1]")

    # no duplicated mobility nominal condition
    mob = robustness_master[(robustness_master["sweep"] == "mobility") & (robustness_master["is_nominal"])]
    n_nominal_conditions = mob[["condition_value_1", "condition_value_2"]].drop_duplicates().shape[0]
    if n_nominal_conditions != 1:
        issues.append(f"mobility: expected exactly 1 nominal condition, found {n_nominal_conditions}")

    # deterministic ordering: condition values strictly non-decreasing within each sweep
    for sweep in robustness_master["sweep"].unique():
        sub = robustness_master[robustness_master["sweep"] == sweep]
        vals = sub[["condition_value_1", "condition_value_2"]].drop_duplicates()
        v1 = vals["condition_value_1"].tolist()
        if v1 != sorted(v1):
            issues.append(f"{sweep}: condition_value_1 not sorted ascending in robustness_master")

    # nominal table sanity: comparison rows algebra vs method-row point estimates
    methods = nominal_df[nominal_df["row_type"] == "method"].set_index("label")
    comps = nominal_df[nominal_df["row_type"] == "comparison"]
    for _, r in comps.iterrows():
        if r["label"] == "LR-PPO family - Lead":
            expected = methods.loc["LR-PPO", "success_rate_pct"] - methods.loc["Lead", "success_rate_pct"]
            if abs(expected - r["diff_pp"]) > 0.02:
                issues.append(f"nominal table: LR-Lead diff mismatch ({expected} vs {r['diff_pp']})")
        if r["label"] == "LR-PPO family - PPO family":
            expected = methods.loc["LR-PPO", "success_rate_pct"] - methods.loc["PPO", "success_rate_pct"]
            if abs(expected - r["diff_pp"]) > 0.02:
                issues.append(f"nominal table: LR-PPO diff mismatch ({expected} vs {r['diff_pp']})")

    return issues


def build_master_manifest(source_commit: str) -> dict:
    sweep_dirs = ["hostile_evasion", "maneuverability", "measurement_noise", "mobility", "detection_radius"]
    source_evidence_hashes = {"lead_residual_expanded_final_5000": json.loads((NOMINAL_ROOT / "evidence_hashes.json").read_text())}
    for sweep in sweep_dirs:
        source_evidence_hashes[sweep] = json.loads((ROBUST_ROOT / sweep / "evidence_hashes.json").read_text())

    generated_files = []
    for sub in ("data", "tables"):
        for f in sorted((PAPER_ROOT / sub).glob("*")):
            if f.is_file():
                generated_files.append(str(f.relative_to(PAPER_ROOT)))
    generated_hashes = {f: sha256_of_file(PAPER_ROOT / f) for f in generated_files}

    model_hashes = json.loads((NOMINAL_ROOT / "model_hashes.json").read_text())

    return {
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "final_experiment_source_commit": source_commit,
        "posthoc_mobility_audit_commit": "6f52570e5be343a5923fb5c822e73e75151ef4ef",
        "evidence_directories": {
            "expanded_final_nominal": str(NOMINAL_ROOT.relative_to(PROJECT_ROOT)),
            **{s: str((ROBUST_ROOT / s).relative_to(PROJECT_ROOT)) for s in sweep_dirs},
            "mobility_posthoc_audit": str((ROBUST_ROOT / "mobility" / "posthoc_audit").relative_to(PROJECT_ROOT)),
        },
        "source_evidence_hashes": source_evidence_hashes,
        "frozen_model_hashes": {k: v["actual"] for k, v in model_hashes.items()},
        "generated_master_artifact_hashes": generated_hashes,
        "new_simulations_run": False,
        "new_training_run": False,
        "new_models_created": False,
        "future_seeds_opened": False,
        "historical_deprecated_evidence_not_used": ["results/robustness/*", "results/paper_evidence/*", "results/paper_figures/*"],
    }


