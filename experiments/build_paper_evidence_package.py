def _classical_row(classical_df, cond_filter, method):
    sub = classical_df[cond_filter & (classical_df["method"] == method)]
    if len(sub) == 0:
        return None
    r = sub.iloc[0]
    return float(r["success_rate"]), float(r["ci_low"]), float(r["ci_high"]), None


def _family_row(family_df, cond_filter, method):
    sub = family_df[cond_filter & (family_df["method"] == method)]
    if len(sub) == 0:
        return None
    r = sub.iloc[0]
    return float(r["mean_success"]), float(r["hierarchical_ci_low"]), float(r["hierarchical_ci_high"]), float(r["between_seed_sd"])


def build_robustness_master() -> pd.DataFrame:
    rows = []

    sweep_specs = [
        ("hostile_evasion", ["gain"], (0.75,)),
        ("maneuverability", ["defender_max_accel", "defender_max_turn_rate_deg"], (8.0, 90.0)),
        ("measurement_noise", ["measurement_var"], (0.50,)),
        ("mobility", ["v_d", "v_e"], (18.0, 12.0)),
        ("detection_radius", ["detection_radius"], (15.0,)),
    ]
    for sweep, cond_cols, nominal_vals in sweep_specs:
        d = ROBUST_ROOT / sweep
        classical = pd.read_csv(d / "classical_summary.csv")
        family = pd.read_csv(d / "family_summary.csv")
        primary = pd.read_csv(d / "primary_comparisons.csv")

        conditions = classical[cond_cols].drop_duplicates().sort_values(cond_cols).to_records(index=False).tolist()
        for cond in conditions:
            cond = tuple(cond)
            filt = pd.Series(True, index=classical.index)
            filt_fam = pd.Series(True, index=family.index)
            filt_pri = pd.Series(True, index=primary.index)
            for col, val in zip(cond_cols, cond):
                filt &= (classical[col] == val)
                filt_fam &= (family[col] == val)
                filt_pri &= (primary[col] == val)
            is_nominal = tuple(round(v, 6) for v in cond) == tuple(round(v, 6) for v in nominal_vals)

            pri_sub = primary[filt_pri]
            lr_lead = pri_sub[pri_sub["comparison"] == "LR-PPO family - Lead"]
            lr_ppo_cmp = pri_sub[pri_sub["comparison"] == "LR-PPO family - PPO family"]
            lr_lead_vals = (float(lr_lead.iloc[0]["diff_pp"]), float(lr_lead.iloc[0]["ci_low_pp"]), float(lr_lead.iloc[0]["ci_high_pp"])) if len(lr_lead) else (None, None, None)
            lr_ppo_vals = (float(lr_ppo_cmp.iloc[0]["diff_pp"]), float(lr_ppo_cmp.iloc[0]["ci_low_pp"]), float(lr_ppo_cmp.iloc[0]["ci_high_pp"])) if len(lr_ppo_cmp) else (None, None, None)

            for method in PAPER_METHODS:
                if method in ("greedy", "pn", "lead"):
                    res = _classical_row(classical, filt, method)
                else:
                    res = _family_row(family, filt_fam, method)
                if res is None:
                    continue
                success, ci_lo, ci_hi, between_sd = res
                is_lr = method == "lr_ppo"
                row = {
                    "sweep": sweep,
                    "condition_label": "|".join(f"{c:g}" for c in cond),
                    "condition_value_1": cond[0],
                    "condition_value_2": cond[1] if len(cond) > 1 else None,
                    "is_nominal": is_nominal,
                    "method": method, "method_role": METHOD_ROLE[method],
                    "success_rate": round(success, 6), "ci_low": round(ci_lo, 6), "ci_high": round(ci_hi, 6),
                    "between_seed_sd": round(between_sd, 6) if between_sd is not None else None,
                    "lr_minus_lead_pp": round(lr_lead_vals[0], 4) if is_lr and lr_lead_vals[0] is not None else None,
                    "lr_minus_lead_ci_low": round(lr_lead_vals[1], 4) if is_lr and lr_lead_vals[1] is not None else None,
                    "lr_minus_lead_ci_high": round(lr_lead_vals[2], 4) if is_lr and lr_lead_vals[2] is not None else None,
                    "lr_minus_ppo_pp": round(lr_ppo_vals[0], 4) if is_lr and lr_ppo_vals[0] is not None else None,
                    "lr_minus_ppo_ci_low": round(lr_ppo_vals[1], 4) if is_lr and lr_ppo_vals[1] is not None else None,
                    "lr_minus_ppo_ci_high": round(lr_ppo_vals[2], 4) if is_lr and lr_ppo_vals[2] is not None else None,
                }
                rows.append(row)
    df = pd.DataFrame(rows)
    df = df.sort_values(["sweep", "condition_value_1", "condition_value_2", "method"], na_position="first").reset_index(drop=True)
    return df


