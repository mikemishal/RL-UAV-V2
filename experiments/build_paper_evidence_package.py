def build_nominal_table() -> pd.DataFrame:
    classical = pd.read_csv(NOMINAL_ROOT / "classical_summary.csv")
    family = pd.read_csv(NOMINAL_ROOT / "family_summary.csv")
    primary = pd.read_csv(NOMINAL_ROOT / "primary_comparisons.csv")

    rows = []
    for method in ("greedy", "pn", "lead"):
        r = classical[classical["method"] == method].iloc[0]
        rows.append({
            "row_type": "method", "label": DISPLAY_NAME[method], "method_role": METHOD_ROLE[method],
            "is_estimator_ablation": False, "n": int(r["n_episodes"]),
            "success_rate_pct": round(100 * r["success_rate"], 2),
            "ci_low_pct": round(100 * r["success_ci_low"], 2), "ci_high_pct": round(100 * r["success_ci_high"], 2),
            "between_root_sd_pct": None,
            "diff_pp": None, "diff_ci_low_pp": None, "diff_ci_high_pp": None,
        })
    for method in ("ppo", "ppo_kalman", "lr_ppo"):
        r = family[family["method"] == method].iloc[0]
        rows.append({
            "row_type": "method", "label": DISPLAY_NAME[method], "method_role": METHOD_ROLE[method],
            "is_estimator_ablation": (method == "ppo_kalman"), "n": int(r["n_training_seeds"]) * 5000,
            "success_rate_pct": round(100 * r["mean_success"], 2),
            "ci_low_pct": round(100 * r["hierarchical_ci_low"], 2), "ci_high_pct": round(100 * r["hierarchical_ci_high"], 2),
            "between_root_sd_pct": round(100 * r["between_seed_sd"], 3),
            "diff_pp": None, "diff_ci_low_pp": None, "diff_ci_high_pp": None,
        })
    for _, r in primary.iterrows():
        rows.append({
            "row_type": "comparison", "label": r["comparison"], "method_role": None,
            "is_estimator_ablation": False, "n": None,
            "success_rate_pct": None, "ci_low_pct": None, "ci_high_pct": None, "between_root_sd_pct": None,
            "diff_pp": round(r["diff_pp"], 2), "diff_ci_low_pp": round(r["ci_low_pp"], 2), "diff_ci_high_pp": round(r["ci_high_pp"], 2),
        })
    return pd.DataFrame(rows)


def write_nominal_latex(df: pd.DataFrame, path: Path):
    methods = df[df["row_type"] == "method"]
    comps = df[df["row_type"] == "comparison"]
    lines = [
        r"% Auto-generated by experiments/build_paper_evidence_package.py -- DO NOT EDIT BY HAND",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Nominal safe-interception performance (expanded-final, 5000 seeds; learned families equal-weighted across 3 training roots). PPO-Kalman is an estimator-ablation diagnostic, not a co-equal proposed method.}",
        r"\label{tab:nominal_performance}",
        r"\begin{tabular}{lccc}",
        r"\toprule",
        r"Method & $n$ & Success rate (\%) & 95\% CI \\",
        r"\midrule",
    ]
    for _, r in methods.iterrows():
        label = r["label"] + (r" (ablation)" if r["is_estimator_ablation"] else "")
        lines.append(f"{label} & {int(r['n'])} & {r['success_rate_pct']:.2f} & [{r['ci_low_pct']:.2f}, {r['ci_high_pct']:.2f}] \\\\")
    lines += [r"\midrule", r"\multicolumn{4}{l}{\textit{Primary nominal comparisons}} \\"]
    for _, r in comps.iterrows():
        lines.append(f"{r['label']} & -- & {r['diff_pp']:.2f}\\,pp & [{r['diff_ci_low_pp']:.2f}, {r['diff_ci_high_pp']:.2f}] \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    path.write_text("\n".join(lines) + "\n")


